// Exports ABIs + bytecode from Foundry artifacts into agent/src/abi/contracts.ts (committed, so the
// TypeScript side and the dashboard never drift from the audited Solidity).
import { readFileSync, writeFileSync } from "node:fs";
const names = [
  ["TestUSD", "TestUSD.sol"],
  ["QEDVault", "QEDVault.sol"],
  ["QEDLens", "QEDLens.sol"],
  ["QEDClearing", "QEDClearing.sol"],
  ["ProofEscrow", "ProofEscrow.sol"],
  ["MinVarianceVerifier", "MinVarianceVerifier.sol"],
  ["Groth16Verifier", "Groth16Verifier.sol"],
  ["PrivateMinVarianceVerifier", "PrivateMinVarianceVerifier.sol"],
  ["OptimalityBounty", "OptimalityBounty.sol"],
  ["MaximalityBounty", "MaximalityBounty.sol"],
  ["QEDExecution", "QEDExecution.sol"],
  ["CPMMPool", "CPMMPool.sol"],
  ["TestToken", "TestToken.sol"],
];
let out = "// AUTO-GENERATED by agent/scripts/export-abi.mjs from Foundry artifacts. Do not edit.\n";
for (const [name, file] of names) {
  const j = JSON.parse(readFileSync(`out/${file}/${name}.json`, "utf8"));
  out += `export const ${name}Abi = ${JSON.stringify(j.abi)} as const;\n`;
  out += `export const ${name}Bytecode = "${j.bytecode.object}" as const;\n`;
}
writeFileSync("agent/src/abi/contracts.ts", out);
console.log("exported", names.map((n) => n[0]).join(", "));
