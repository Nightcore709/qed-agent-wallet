/**
 * Generates contracts/test/fixtures/ExecutionFixture.sol from the TypeScript engine, so the Solidity
 * tests check the contract against the agent's solver, simulator and bound replica bit for bit.
 *   npx tsx agent/scripts/fixtures-execution.ts
 */
import { writeFileSync } from "node:fs";
import type { Address } from "viem";
import { bestSingleVenue, equalSplitDirect, optimalDirectOnly, simulate, solve, dualBound, PRICE_ONE, type Hop, type VenueState } from "../src/engine/execution.js";
import { EXEC_VENUES, raw, SLIPPAGE_BPS, TRADE_TUSD, type Sym } from "../src/engine/executionScenario.js";

const SYMS: Sym[] = ["tUSD", "tEUR", "tETH"];
const ADDR: Record<Sym, Address> = {
  tUSD: "0x0000000000000000000000000000000000000a01",
  tEUR: "0x0000000000000000000000000000000000000a02",
  tETH: "0x0000000000000000000000000000000000000a03",
};
const symOf = (a: string) => SYMS.find((s) => ADDR[s].toLowerCase() === a.toLowerCase())!;
const venues: VenueState[] = EXEC_VENUES.map((v, i) => {
  const [x, y] = ADDR[v.a] < ADDR[v.b] ? [v.a, v.b] : [v.b, v.a];
  const rx = x === v.a ? raw(v.a, v.ra) : raw(v.b, v.rb);
  const ry = x === v.a ? raw(v.b, v.rb) : raw(v.a, v.ra);
  return { pool: `0x00000000000000000000000000000000000b0${i}` as Address, token0: ADDR[x], token1: ADDR[y], r0: rx, r1: ry, feeBps: v.feeBps };
});
const A = raw("tUSD", TRADE_TUSD);
const plan = solve(venues, ADDR.tUSD, ADDR.tEUR, A);
if (!plan.sim.ok) throw new Error("honest plan does not simulate: " + plan.sim.error);
const minOut = (plan.sim.amountOut * BigInt(10_000 - SLIPPAGE_BPS)) / 10_000n;

// attacks
const direct = optimalDirectOnly(venues, ADDR.tUSD, ADDR.tEUR, A)!.route;
const single = bestSingleVenue(venues, ADDR.tUSD, ADDR.tEUR, A)!;
const equal = equalSplitDirect(venues, ADDR.tUSD, ADDR.tEUR, A)!;
const nudged = plan.route.map((h) => ({ ...h }));
{
  const src = nudged.filter((h) => h.amountIn > 0n && (h.zeroForOne ? venues[h.venue].token0 : venues[h.venue].token1) === ADDR.tUSD);
  src.sort((a, b) => (a.amountIn > b.amountIn ? -1 : 1));
  const shift = src[0].amountIn / 20n; // move 5% of the largest leg to the second
  src[0].amountIn -= shift;
  src[1].amountIn += shift;
}
const leftover = plan.route.filter((h) => (h.zeroForOne ? venues[h.venue].token0 : venues[h.venue].token1) !== ADDR.tETH);
const forged = new Map(plan.prices);
const directPlan = solve(venues.filter((v) => v.token0 !== ADDR.tETH && v.token1 !== ADDR.tETH), ADDR.tUSD, ADDR.tEUR, A);
forged.set(ADDR.tUSD.toLowerCase(), directPlan.prices.get(ADDR.tUSD.toLowerCase())!);
forged.set(ADDR.tETH.toLowerCase(), (plan.prices.get(ADDR.tETH.toLowerCase())! * 9n) / 10n);

const routes: Record<string, Hop[]> = { honest: plan.route, directOnly: direct, nudged, single, equal, leftover };
const sims = Object.fromEntries(Object.entries(routes).map(([k, r]) => [k, simulate(venues, r, ADDR.tUSD, ADDR.tEUR, A)]));
for (const k of ["directOnly", "nudged"]) {
  if (sims[k].amountOut < minOut) throw new Error(`${k} should pass the slippage floor`);
  if (sims[k].amountOut * 1_000_000n >= plan.bound * 999_999n) throw new Error(`${k} should fail best execution`);
}
if (sims.single.amountOut >= minOut) throw new Error("single should fail the slippage floor");
const forgedBound = dualBound(venues, A, ADDR.tUSD, ADDR.tEUR, forged);

const sell = (h: Hop) => SYMS.indexOf(symOf(h.zeroForOne ? venues[h.venue].token0 : venues[h.venue].token1));
const hops = (r: Hop[]) => r.map((h) => `H(${h.venue}, ${sell(h)}, ${h.amountIn})`).join(", ");
const priceArr = (p: Map<string, bigint>) => SYMS.map((s) => (p.get(ADDR[s].toLowerCase()) ?? 0n).toString());
const fn = (name: string, r: Hop[]) => `    function ${name}() internal pure returns (H[] memory r) {\n        r = new H[](${r.length});\n${r.map((h, i) => `        r[${i}] = H(${h.venue}, ${sell(h)}, ${h.amountIn});`).join("\n")}\n    }`;
void hops;

const sol = `// SPDX-License-Identifier: MIT
// GENERATED by agent/scripts/fixtures-execution.ts from agent/src/engine/{execution,executionScenario}.ts. Do not edit.
pragma solidity 0.8.26;

/// @dev Token symbols: 0 = tUSD (6 dp), 1 = tEUR (6 dp), 2 = tETH (18 dp).
library ExecutionFixture {
    struct V {
        uint8 a;
        uint256 ra;
        uint8 b;
        uint256 rb;
        uint16 feeBps;
    }

    /// @dev One hop: venue index, symbol sold, amount (0 = everything received so far).
    struct H {
        uint8 venue;
        uint8 sell;
        uint256 amountIn;
    }

    uint256 internal constant AMOUNT_IN = ${A};
    uint256 internal constant MIN_OUT = ${minOut};
    uint256 internal constant HONEST_BOUND = ${plan.bound};
    uint256 internal constant HONEST_OUT = ${sims.honest.amountOut};
    uint256 internal constant DIRECT_ONLY_OUT = ${sims.directOnly.amountOut};
    uint256 internal constant NUDGED_OUT = ${sims.nudged.amountOut};
    uint256 internal constant SINGLE_OUT = ${sims.single.amountOut};
    uint256 internal constant EQUAL_OUT = ${sims.equal.amountOut};
    uint256 internal constant FORGED_BOUND = ${forgedBound};

    function venues() internal pure returns (V[] memory v) {
        v = new V[](${EXEC_VENUES.length});
${EXEC_VENUES.map((v, i) => `        v[${i}] = V(${SYMS.indexOf(v.a)}, ${raw(v.a, v.ra)}, ${SYMS.indexOf(v.b)}, ${raw(v.b, v.rb)}, ${v.feeBps});`).join("\n")}
    }

    /// @dev ν per symbol, × 1e36; ν(tEUR) = 1e36.
    function honestPrices() internal pure returns (uint256[3] memory) {
        return [uint256(${priceArr(plan.prices).join("), uint256(")})];
    }

    function forgedPrices() internal pure returns (uint256[3] memory) {
        return [uint256(${priceArr(forged).join("), uint256(")})];
    }

${Object.entries(routes).map(([k, r]) => fn(k, r)).join("\n\n")}
}
`;
writeFileSync("contracts/test/fixtures/ExecutionFixture.sol", sol);
console.log(`honest: out ${sims.honest.amountOut} bound ${plan.bound} gap ${plan.gapPpm} ppm, ${plan.iterations} sweeps; PRICE_ONE ${PRICE_ONE}`);
for (const [k, s] of Object.entries(sims)) console.log(`  ${k.padEnd(11)} out ${s.amountOut.toString().padStart(10)}  loss ${((Number(plan.sim.amountOut - s.amountOut) / Number(plan.sim.amountOut)) * 1e4).toFixed(3)} bps ${s.error ?? ""}`);
console.log(`  minOut ${minOut}; forged bound ${forgedBound} (≥ honest bound ${plan.bound})`);
