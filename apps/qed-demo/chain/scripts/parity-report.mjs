/**
 * Writes results/PARITY-GATE.md from every results/gate/<tier>-node<version>/summary.json.
 *   node scripts/parity-report.mjs
 * It only reads saved summaries; it runs nothing. Numbers in the report are therefore exactly the recorded ones.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = resolve(fileURLToPath(new URL("..", import.meta.url)));
const gateDir = join(PKG, "results", "gate");
const runs = existsSync(gateDir)
  ? readdirSync(gateDir).sort().map((d) => join(gateDir, d, "summary.json")).filter(existsSync).map((p) => JSON.parse(readFileSync(p, "utf8")))
  : [];

const L = [];
L.push("# First parity gate: the release's own suites, run in the workspace copy");
L.push("");
L.push("Generated by `scripts/parity-report.mjs` from the saved summaries under `results/gate/`. Raw output of every");
L.push("command is beside each summary. Nothing in the approved release was built, installed or run: the suites ran in");
L.push("a disposable copy of `vendor/` assembled by `scripts/assemble-tree.mjs` and checked against `VENDORED.json`.");
L.push("");
L.push("Reference: the release's own saved run (`~/qed-approved-release/review/deploy-20261025/qa-node22/SUMMARY.txt`,");
L.push("Node v22.23.3, Anvil 1.7.1) passed 305 tests under eight labels: focused-ui 62, typescript-tests 64, solidity 147,");
L.push("backend-unit 8, live-local-sandbox 10, workbench 10, release-safety 4, plus the type check.");
L.push("");
if (!runs.length) L.push("No gate run has been recorded yet.");
for (const r of runs) {
  L.push(`## Tier \`${r.tier}\` · Node ${r.versions.node} · ${r.versions.anvil} · solc ${r.versions.solc}`);
  L.push("");
  L.push(`Run ${r.startedAt} to ${r.finishedAt}. Tree: ${r.tree.files} vendored files${r.tree.withZk ? " (default tier plus the zk-optional tier)" : " (default tier only: no GPL-3.0 source or package)"}.`);
  L.push(`Environment: QED_OFFLINE=1, no model key, SOLC_VERSION=${r.versions.solc}, FOUNDRY_OFFLINE=true. Loopback only.`);
  L.push("");
  L.push("| Label | Release command | Release tests | Run here | Passed | Failed | Result |");
  L.push("|---|---|---:|---:|---:|---:|---|");
  for (const s of r.suites) {
    const res = s.ok === null ? "not run in this tier" : s.ok ? "pass" : "FAIL";
    const isCount = s.releaseTests !== null;
    L.push(`| ${s.label} | \`${s.releaseCommand.length > 70 ? s.releaseCommand.slice(0, 67) + "…" : s.releaseCommand}\` | ${isCount ? s.releaseTests : "n/a"} | ${isCount ? s.tests : "n/a"} | ${isCount ? s.pass : "n/a"} | ${isCount ? s.fail : (s.runs[0]?.errors ?? "n/a")} | ${res} |`);
  }
  L.push(`| **Total** | | **${r.totals.releaseTestsForTheseLabels}** | **${r.totals.tests}** | **${r.totals.pass}** | **${r.totals.fail}** | ${r.totals.allRunSuitesPassed ? "all run suites pass" : "FAILURES"} |`);
  L.push("");
  L.push(`Accounting: ${r.totals.releaseTestsForTheseLabels} in the release = ${r.totals.tests} run here + ${r.totals.releaseTestsNotRunHere} not run here.`);
  L.push("");
  L.push("Per file:");
  L.push("");
  L.push("| Label | File | Tests | Passed | Failed | Seconds | Note |");
  L.push("|---|---|---:|---:|---:|---:|---|");
  for (const s of r.suites) {
    for (const run of s.runs) {
      if (run.suites) {
        for (const fs of run.suites) L.push(`| ${s.label} | ${fs.suite} | ${fs.passed + fs.failed + fs.skipped} | ${fs.passed} | ${fs.failed} | | |`);
        continue;
      }
      if (run.notRun) { L.push(`| ${s.label} | ${run.file} | | | | | not run: see below |`); continue; }
      if (run.blocked) { L.push(`| ${s.label} | ${run.file} | | | | | BLOCKED: ${run.reason} |`); continue; }
      if (run.errors !== undefined) { L.push(`| ${s.label} | ${run.command} | | | ${run.errors} errors | ${run.seconds} | |`); continue; }
      L.push(`| ${s.label} | ${run.file} | ${run.tests} | ${run.pass} | ${run.fail} | ${run.seconds} | ${run.oldPageMarkup ? "asserts the old page's markup; passes on the vendored fixture, not a parity target for the new interface" : ""}${run.orphanedAnvilStopped ? " orphaned Anvil stopped after the run" : ""} |`);
    }
  }
  L.push("");
  const failures = r.suites.flatMap((s) => s.runs.filter((x) => (x.fail ?? 0) > 0 || (x.failures?.length ?? 0) > 0 || (x.exit !== undefined && x.exit !== 0)).map((x) => ({ label: s.label, ...x })));
  L.push(failures.length ? "Failures:" : "Failures: none.");
  for (const f of failures) L.push(`- ${f.label} · ${f.file ?? f.command}: exit ${f.exit}; failing tests: ${(f.failures ?? []).join("; ") || "(see raw output)"}`);
  L.push("");
  L.push("Not run in this tier, and why:");
  L.push("");
  for (const n of r.notRun) L.push(`- \`${n.file}\` (${n.label}${n.releaseTests ? `, ${n.releaseTests} tests` : ""}): ${n.reason}`);
  L.push("");
}
writeFileSync(join(PKG, "results", "PARITY-GATE.md"), L.join("\n") + "\n");
console.log(`wrote results/PARITY-GATE.md from ${runs.length} run(s)`);
