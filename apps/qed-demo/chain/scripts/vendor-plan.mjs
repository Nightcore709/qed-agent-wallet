const JUNK = [/(^|\/)\.DS_Store$/];

function walk(root, rel, out) {
  const abs = join(root, rel);
  const st = lstatSync(abs);
  if (st.isSymbolicLink()) throw new Error(`Refusing a symbolic link in the release: ${rel}`);
  if (st.isDirectory()) {
    for (const name of readdirSync(abs).sort()) walk(root, `${rel}/${name}`, out);
  } else if (st.isFile()) out.push(rel);
}

/** Expands RULES against a release folder. Returns [{source, tier, note, licence}] sorted by source. */
export function expandPlan(releaseRoot) {
  const never = new Set(NEVER.map((n) => n.source));
  const seen = new Map();
  for (const rule of RULES) {
    const found = [];
    if (rule.kind === "file") found.push(rule.source);
    else walk(releaseRoot, rule.source, found);
    for (const source of found) {
      if (JUNK.some((re) => re.test(source))) continue;
      if (never.has(source)) continue;
      if (rule.kind === "dir" && rule.exclude.some((re) => re.test(source))) continue;
      if (seen.has(source)) continue;
      const zk = ZK_TIER.get(source);
      seen.set(source, zk ? { source, tier: "zk-optional", note: zk.why, licence: zk.licence } : { source, tier: "default", note: rule.note, licence: licenceOf(source) });
    }
  }
  for (const source of ZK_TIER.keys()) if (!seen.has(source)) throw new Error(`zk-optional file not found in the release: ${source}`);
  return [...seen.values()].sort((a, b) => (a.source < b.source ? -1 : a.source > b.source ? 1 : 0));
}

export function licenceOf(source) {
  if (source.startsWith("lib/forge-std/")) return "MIT OR Apache-2.0";
  if (source.startsWith("lib/openzeppelin-contracts/")) return "MIT";
  if (source === "agent/src/abi/contracts.ts") return "MIT (embeds bytecode compiled from the GPL-3.0 Groth16Verifier.sol; the default rail never deploys it)";
  return "MIT";
}
