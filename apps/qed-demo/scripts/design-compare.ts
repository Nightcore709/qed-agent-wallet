/**
 * Compares two runs of scripts/design-measures.ts screen by screen (R7-112: measured before and after).
 *
 *   node scripts/design-compare.ts <before-label> <after-label> [--new /save,/protect]
 *
 * --new names screens the earlier design did not have (it drew its not-found page there); they are shown as new and
 * left out of the totals.
 *
 * Reads evidence/design/<label>/measures.json for both and writes evidence/design/<after-label>/compare.md. Detail
 * screens are matched by kind (an instruction, a record), since the two fixtures hold different ids for the same
 * seeded activity. Each figure is the instrument's proxy as defined in design-measures.ts, not a verdict on taste.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

type M = {
  words: number; wordsFirst: number; sizes: number[]; colours: number; contrastMin: number | null; contrastFails: number
  targets: number; small24: number; under32: number; blankFirst: number; inkFirst: number; blankPage: number; edgesFirst: number
  overflow: boolean; axe: Record<string, number>; fault: boolean
}
const dir = join(import.meta.dirname, '..', 'evidence', 'design')
const [beforeLabel, afterLabel] = process.argv.slice(2)
const fresh = new Set((process.argv.includes('--new') ? process.argv[process.argv.indexOf('--new') + 1] ?? '' : '').split(',').filter(Boolean))
if (!beforeLabel || !afterLabel) throw new Error('usage: node scripts/design-compare.ts <before-label> <after-label>')
const load = (l: string) => JSON.parse(readFileSync(join(dir, l, 'measures.json'), 'utf8')) as { at: string; base: string; results: Record<string, M> }
const before = load(beforeLabel), after = load(afterLabel)
const kind = (route: string) => route.replace(/^\/instructions\/(?!new$)[^/]+$/, '/instructions/:id').replace(/^\/record\/[^/]+$/, '/record/:id').replace(/^\/evidence\/[^/]+$/, '/evidence/:id')
const index = (r: Record<string, M>) => {
  const o = new Map<string, M>()
  for (const [k, v] of Object.entries(r)) { const [route, w, theme] = k.split(' '); o.set(`${kind(route!)} ${w} ${theme}`, v) }
  return o
}
const b = new Map([...index(before.results)].filter(([k]) => !fresh.has(k.split(' ')[0]!))), a = index(after.results)
const routes = [...new Set([...a.keys()].map((k) => k.split(' ')[0]!))]
const axeSum = (m?: M) => (m ? Object.values(m.axe).reduce((s, n) => s + n, 0) : 0)
const pair = (x: number | string | null | undefined, y: number | string | null | undefined) => `${x ?? '–'} → ${y ?? '–'}`
const lines: string[] = [
  `# Design measures: ${beforeLabel} → ${afterLabel}`,
  '',
  `Before: \`evidence/design/${beforeLabel}/measures.json\` (${before.at}). After: \`evidence/design/${afterLabel}/measures.json\` (${after.at}).`,
  'Generated by `scripts/design-compare.ts`; definitions in `scripts/design-measures.ts`. Each cell is before → after.',
  'Contrast failures and axe violations are summed over light and dark; the rest are read in light.',
  '',
]
const totals = { sizesB: 0, sizesA: 0, under32B: 0, under32A: 0, small24B: 0, small24A: 0, contrastB: 0, contrastA: 0, axeB: 0, axeA: 0, firstB: 0, firstA: 0, blankB: 0, blankA: 0, n: 0 }
for (const w of ['1440', '390']) {
  lines.push(`## ${w} px`, '', '| Screen | Words (first window) | Type sizes | Text colours | Controls under 32 px | Under 24 px | Contrast fails | Largest blank (first window) | Edges | axe | Overflow |', '|---|---|---|---|---|---|---|---|---|---|---|')
  for (const r of routes) {
    const ab = a.get(`${r} ${w} light`), bb = b.get(`${r} ${w} light`)
    const ad = a.get(`${r} ${w} dark`), bd = b.get(`${r} ${w} dark`)
    if (!ab) continue
    const cf = (l?: M, d?: M) => (l && d ? l.contrastFails + d.contrastFails : undefined)
    const ax = (l?: M, d?: M) => (l && d ? axeSum(l) + axeSum(d) : undefined)
    const pct = (m?: M) => (m ? `${Math.round(m.blankFirst * 100)}%` : undefined)
    lines.push(`| \`${r}\`${bb ? '' : ' (new)'} | ${pair(bb?.wordsFirst, ab.wordsFirst)} | ${pair(bb?.sizes.length, ab.sizes.length)} | ${pair(bb?.colours, ab.colours)} | ${pair(bb?.under32, ab.under32)} | ${pair(bb?.small24, ab.small24)} | ${pair(cf(bb, bd), cf(ab, ad))} | ${pair(pct(bb), pct(ab))} | ${pair(bb?.edgesFirst, ab.edgesFirst)} | ${pair(ax(bb, bd), ax(ab, ad))} | ${pair(bb ? String(bb.overflow) : undefined, String(ab.overflow))} |`)
    if (bb && bd && ad) {
      totals.n++
      totals.sizesB += bb.sizes.length; totals.sizesA += ab.sizes.length
      totals.under32B += bb.under32; totals.under32A += ab.under32
      totals.small24B += bb.small24; totals.small24A += ab.small24
      totals.contrastB += bb.contrastFails + bd.contrastFails; totals.contrastA += ab.contrastFails + ad.contrastFails
      totals.axeB += axeSum(bb) + axeSum(bd); totals.axeA += axeSum(ab) + axeSum(ad)
      totals.firstB += bb.wordsFirst; totals.firstA += ab.wordsFirst
      totals.blankB += bb.blankFirst; totals.blankA += ab.blankFirst
    }
  }
  lines.push('')
}
const avg = (x: number) => (totals.n ? Math.round((x / totals.n) * 10) / 10 : 0)
lines.push(
  '## Over the screens both designs have (both widths)',
  '',
  `| Measure | Before | After |`, '|---|---:|---:|',
  `| Screens compared (width x screen) | ${totals.n} | ${totals.n} |`,
  `| Type sizes per screen, mean | ${avg(totals.sizesB)} | ${avg(totals.sizesA)} |`,
  `| Controls under 32 px, total | ${totals.under32B} | ${totals.under32A} |`,
  `| Controls under 24 px, total | ${totals.small24B} | ${totals.small24A} |`,
  `| Text under its contrast minimum, total (light and dark) | ${totals.contrastB} | ${totals.contrastA} |`,
  `| axe WCAG 2.2 AA violations, total nodes (light and dark) | ${totals.axeB} | ${totals.axeA} |`,
  `| Words in the first window, mean | ${avg(totals.firstB)} | ${avg(totals.firstA)} |`,
  `| Largest blank in the first window, mean share | ${Math.round(avg(totals.blankB * 100))}% | ${Math.round(avg(totals.blankA * 100))}% |`,
  '',
)
writeFileSync(join(dir, afterLabel, 'compare.md'), `${lines.join('\n')}\n`)
console.log(lines.slice(-12).join('\n'))
