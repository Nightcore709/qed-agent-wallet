/**
 * docs/PERMISSIONS.md, generated from the API's own route table (server/api.ts routeTable; ASVS 5.0 V8.1.1, V8.2.1).
 *
 *   node scripts/permissions.ts            write docs/PERMISSIONS.md
 *   node scripts/permissions.ts --check    exit 1 if the document differs from what the code enforces
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export async function permissionsDocument(): Promise<string> {
  const { routeTable } = await import('../server/api.ts')
  const rows = routeTable()
  const least = (l: string): string => (l === 'person' ? 'the person (any workspace)' : l)
  const lines = [
    '# Who may call what: the API\'s permission table',
    '',
    'Generated by `node scripts/permissions.ts` from the routes in `server/api.ts` (`routeTable`); `server/permissions.test.ts`',
    'fails if this file and the code differ. Do not edit by hand.',
    '',
    'How to read it (ASVS 5.0 V8.1.1, V8.2.1):',
    '',
    '- **Session**: `yes`, the route refuses a request without a live session (401); `no`, it is a sign-in, sign-up, recovery or',
    '  public read, protected instead by the Origin and `X-QED-Client` checks, rate limits and a uniform answer.',
    '- **Least role**: the lowest role in the workspace the session acts in that may call it (owner > admin > approver > operator',
    '  > viewer); `the person` means it is about the signed-in person, whatever workspace they act in. Every object is then',
    '  loaded with the workspace\'s id in the query: no route takes a user id (object-level access).',
    '- **Further checks**: what the handler asks before it acts. "fresh passkey": a passkey confirmation within five minutes;',
    '  "past its cool-off": by a passkey added more than 24 hours ago (RISK-068, Q-062); "protective": switching protection',
    '  off needs an approver and a passkey. Handlers below the route make more (approval signatures over exact terms, policy',
    '  limits, maker and checker): those are in `SECURITY.md`.',
    '- **Writes**: `one`, the whole request is one database transaction (brief item 2); `own`, an asynchronous handler that',
    '  waits on a passkey check, a password hash or another service, whose writes after each wait are transactions of their',
    '  own; `reads`, a GET.',
    '- Business-workspace roles and what each may do: `server/workspaces.ts`; field-level rules: `SECURITY.md`, "Authorization".',
    '',
    `${rows.length} routes.`,
    '',
    '| Method | Path | Session | Least role | Further checks | Writes |',
    '|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.method} | \`${r.path}\` | ${r.session ? 'yes' : 'no'} | ${least(r.least)} | ${r.checks.join('; ') || 'none'} | ${r.transaction} |`),
    '',
  ]
  return lines.join('\n')
}

if (import.meta.main) {
  const file = join(import.meta.dirname, '..', 'docs', 'PERMISSIONS.md')
  const doc = await permissionsDocument()
  if (process.argv.includes('--check')) {
    const same = readFileSync(file, 'utf8') === doc
    console.log(same ? 'docs/PERMISSIONS.md matches the code.' : 'docs/PERMISSIONS.md differs from the code: run node scripts/permissions.ts')
    process.exit(same ? 0 : 1)
  }
  writeFileSync(file, doc)
  console.log(`Wrote ${file}`)
  process.exit(0)
}
