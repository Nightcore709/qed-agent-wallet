/**
 * Flow envelopes: what delegated money programs can do over time, worked out exactly.
 *
 * Every flow is described by an envelope rather than a forecast. For money that leaves, the most that can have left
 * over any stretch; for money that arrives, the least that is certain to have arrived. From those, three things
 * follow without sampling anything:
 *   reserve       a balance from which nothing already due can fail inside the horizon. It is the least such
 *                 balance (from one paisa less something can) when the flows are independent, debits come before
 *                 inflows inside a day and every listed amount can be charged in full.
 *   most          the most a set of signed limits lets through in a stretch of days
 *   largestMonthlyLimit   the most generous limit a new instruction could be signed with and stay safe
 *
 * Specification, tests against exhaustive search and experiments: experiments/r6/E1-flow-envelopes. This file is a
 * second implementation of that specification; envelope.test.ts checks it against fixtures generated by the Python
 * reference, so a mistake in either shows as a disagreement.
 *
 * Integers only (paise). One step is one day. Inside a step, in the order least favourable to the owner:
 * elastic spending, then committed debits, then inflows.
 */

/** Committed debits of known worst-case size at known steps. */
export interface Scheduled { type: 'scheduled'; at: [step: number, amount: number][] }
/** Committed spending that cannot be postponed: at most this much in any one step. */
export interface Rate { type: 'rate'; perStep: number }
/**
 * A recurring inflow. Payment k is due at step due[k]. Assumed: a payment that arrives does so within lateBy steps
 * of its due step, and up to `missing` outstanding payments may never arrive. `received` lists the ones that have.
 */
export interface Income { type: 'income'; amount: number; due: number[]; lateBy: number; missing: number; received: number[] }
/** The limits written on a signed instruction, on fixed calendar windows, with what has been used so far. */
export interface Caps {
  type: 'caps'; perRun: number; perMonth: number; perDay: number | null
  /** Steps at which a run can happen; null when a run may happen at any step. */
  runSteps: number[] | null
  /** How many runs may fall in one step on which a run can happen. */
  runsPerStep: number
  /** The most over the whole life, and the step at or after which nothing runs; null for none. */
  lifetime: number | null; expires: number | null
  /** The calendar date of step 0, as YYYY-MM-DD. */
  start: string
  usedMonth: number; usedLife: number
}
export type Outflow = Scheduled | Rate | Caps

const prefix = (per: number[]): number[] => { let s = 0; return per.map((v) => (s += v)) }

/** The calendar month a step falls in, as a single number that increases month by month. */
export function monthOf(start: string, step: number): number {
  const d = new Date(Date.parse(`${start}T00:00:00Z`) + step * 86_400_000)
  return d.getUTCFullYear() * 12 + d.getUTCMonth()
}

function stepCapacity(c: Caps, runs: Set<number> | null, step: number): number {
  if (c.expires !== null && step >= c.expires) return 0
  if (runs !== null && !runs.has(step)) return 0
  const cap = c.perRun * c.runsPerStep
  return c.perDay === null ? cap : Math.min(cap, c.perDay)
}

/**
 * The most that can be moved in steps u .. v-1. When `now` is given and u is in the same month as `now`, that month
 * has only perMonth - usedMonth left. Days nest inside months and months inside the life, so the bottom-up sum is exact.
 */
export function most(c: Caps, u: number, v: number, now: number | null = null, runs: Set<number> | null = c.runSteps ? new Set(c.runSteps) : null): number {
  let total = 0, month: number | null = null, inMonth = 0, room = 0
  const nowMonth = now === null ? null : monthOf(c.start, now)
  for (let s = u; s < v; s++) {
    const m = monthOf(c.start, s)
    if (m !== month) { total += inMonth; month = m; inMonth = 0; room = c.perMonth - (m === nowMonth ? c.usedMonth : 0) }
    inMonth = Math.min(Math.max(0, room), inMonth + stepCapacity(c, runs, s))
  }
  total += inMonth
  if (c.lifetime !== null) total = Math.min(total, Math.max(0, c.lifetime - c.usedLife))
  return total
}

/** For each k, the most the flow can have taken over steps now .. now+k. */
export function cumUpper(f: Outflow, now: number, horizon: number): number[] {
  if (f.type === 'rate') return Array.from({ length: horizon }, (_, k) => f.perStep * (k + 1))
  if (f.type === 'scheduled') {
    const per = new Array<number>(horizon).fill(0)
    for (const [step, amount] of f.at) if (step >= now && step < now + horizon) per[step - now]! += amount
    return prefix(per)
  }
  // One pass with running state gives the same numbers as calling most() for every k, in linear time.
  const runs = f.runSteps ? new Set(f.runSteps) : null
  const out: number[] = []
  let done = 0, month: number | null = null, inMonth = 0, room = 0
  const nowMonth = monthOf(f.start, now)
  for (let k = 0; k < horizon; k++) {
    const s = now + k, m = monthOf(f.start, s)
    if (m !== month) { done += inMonth; month = m; inMonth = 0; room = f.perMonth - (m === nowMonth ? f.usedMonth : 0) }
    inMonth = Math.min(Math.max(0, room), inMonth + stepCapacity(f, runs, s))
    const total = done + inMonth
    out.push(f.lifetime === null ? total : Math.min(total, Math.max(0, f.lifetime - f.usedLife)))
  }
  return out
}

/** For each k, the least the income is certain to have brought over steps now .. now+k. */
export function cumLower(f: Income, now: number, horizon: number): number[] {
  const got = new Set(f.received)
  const lapsed = f.due.filter((d, k) => !got.has(k) && d + f.lateBy < now).length
  const allowed = Math.max(0, f.missing - lapsed)
  // "Earliest" is by due step, whatever order `due` is written in (review finding D-2). The sort is stable.
  const outstanding = f.due.map((d, k) => [d, k] as const).filter(([d, k]) => !got.has(k) && d + f.lateBy >= now).sort((a, b) => a[0] - b[0])
  const per = new Array<number>(horizon).fill(0)
  for (const [d] of outstanding.slice(allowed)) { const s = d + f.lateBy - now; if (s < horizon) per[s]! += f.amount }
  return prefix(per)
}

/**
 * How many payments have failed to arrive beyond what the owner allowed for: payments not received whose last
 * possible step has passed, less `missing`. Above zero, reality has left the envelope: the lower envelope still
 * gives a figure (those payments count for nothing and no further miss is allowed), but the stated assumption no
 * longer describes this flow, and whoever shows the reserve must say so.
 */
export function incomeExceeded(f: Income, now: number): number {
  const got = new Set(f.received)
  return Math.max(0, f.due.filter((d, k) => !got.has(k) && d + f.lateBy < now).length - f.missing)
}

export interface Reserve {
  /** The least balance, just before today's debits, from which nothing due can fail. */
  need: number
  /** The step whose debit is the hardest to meet; null when nothing is needed. */
  bindingStep: number | null
  debitsToBinding: number
  inflowsToBinding: number
  /** The same requirement at each later step, if the worst case unfolds and nothing elastic happens. */
  path: number[]
  /** False when the horizon ends with debits still outrunning certain inflows: the figure is then a lower bound. */
  sustainable: boolean
}

/** need = max over k of [ cumOut[k] - cumIn[k-1] ]+ , with cumIn[-1] = 0. */
export function reserveFrom(cumOut: number[], cumIn: number[], now: number): Reserve {
  const n = cumOut.length
  const before = (k: number): number => (k > 0 ? cumIn[k - 1]! : 0)
  let need = 0, arg: number | null = null
  for (let k = 0; k < n; k++) { const gap = cumOut[k]! - before(k); if (gap > need) { need = gap; arg = k } }
  const path = new Array<number>(n).fill(0)
  let best = 0
  for (let k = n - 1; k >= 0; k--) {
    best = Math.max(best, cumOut[k]! - before(k))
    path[k] = Math.max(0, best - (k > 0 ? cumOut[k - 1]! - cumIn[k - 1]! : 0))
  }
  const tail = n > 0 ? cumOut[n - 1]! - (n > 1 ? cumIn[n - 2]! : 0) : 0
  return {
    need, bindingStep: arg === null ? null : now + arg, debitsToBinding: arg === null ? 0 : cumOut[arg]!, inflowsToBinding: arg === null ? 0 : before(arg),
    path, sustainable: !(arg === n - 1 && tail > 0),
  }
}

const sumCurves = (curves: number[][], horizon: number): number[] => { const out = new Array<number>(horizon).fill(0); for (const c of curves) for (let k = 0; k < horizon; k++) out[k]! += c[k]!; return out }

export function reserve(committed: Outflow[], inflows: Income[], now: number, horizon: number): Reserve {
  return reserveFrom(sumCurves(committed.map((f) => cumUpper(f, now, horizon)), horizon), sumCurves(inflows.map((f) => cumLower(f, now, horizon)), horizon), now)
}

/** Cumulative spending of an agent that takes, at every step, as much as its limits and the allowance let it. */
export function greedyDrain(allow: number[], c: Caps, now: number): number[] {
  const runs = c.runSteps ? new Set(c.runSteps) : null
  const spentIn = new Map<number, number>([[monthOf(c.start, now), c.usedMonth]])
  let life = c.usedLife, taken = 0
  return allow.map((a, k) => {
    const s = now + k, m = monthOf(c.start, s)
    let room = Math.min(stepCapacity(c, runs, s), c.perMonth - (spentIn.get(m) ?? 0), a - taken)
    if (c.lifetime !== null) room = Math.min(room, c.lifetime - life)
    room = Math.max(0, room)
    spentIn.set(m, (spentIn.get(m) ?? 0) + room)
    life += room; taken += room
    return taken
  })
}

/**
 * The largest per-month limit, as a whole number of runs of perRun, with which a new instruction running up to
 * runsPerStep times at each of runSteps could be signed such that, even if every run takes its full amount, nothing
 * due inside the horizon can fail. A larger limit never lowers the reserve, so a bisection finds it.
 *
 * What it does not promise (independent review of 20 November 2026, Theorem 5 and its counterexamples): "largest"
 * is among whole numbers of runs that fall inside the horizon; run days beyond it are not looked at, and with no
 * run day in view the answer is 0 because nothing was examined. And "no run is ever refused for want of money"
 * is a theorem only when every later reserve looks to the same end date. With a look-ahead that moves forward
 * each day, as the wallet's does, a debit that comes into view later can make a run be refused.
 */
export function largestMonthlyLimit(balance: number, committed: Outflow[], inflows: Income[], now: number, horizon: number, perRun: number, runSteps: number[], start: string, runsPerStep = 1): number {
  const safe = (runs: number): boolean => {
    if (runs === 0) return reserve(committed, inflows, now, horizon).need <= balance
    const extra: Caps = { type: 'caps', perRun, perMonth: runs * perRun, perDay: null, runSteps, runsPerStep, lifetime: null, expires: null, start, usedMonth: 0, usedLife: 0 }
    return reserve([...committed, extra], inflows, now, horizon).need <= balance
  }
  const visible = [...new Set(runSteps)].filter((s) => s >= now && s < now + horizon).length
  if (visible === 0 || !safe(0)) return 0
  let lo = 0, hi = Math.min(10_000, visible * runsPerStep)
  while (lo < hi) { const mid = Math.floor((lo + hi + 1) / 2); if (safe(mid)) lo = mid; else hi = mid - 1 }
  return lo * perRun
}
